const fs = require('node:fs');
const path = require('node:path');
const sourceRoot = process.env.CODEX_AGENT_SOURCE_ROOT;
if (!sourceRoot) throw new Error('Set CODEX_AGENT_SOURCE_ROOT to the independently available Agent source checkout (containing server/src/board.js). This source is not bundled.');
const boardPath = path.resolve(sourceRoot, 'server/src/board.js');
if (!fs.existsSync(boardPath)) throw new Error('Cannot find server/src/board.js under CODEX_AGENT_SOURCE_ROOT.');
const { DelmBoard } = require(boardPath);
(async () => {
  const b = new DelmBoard({actors:['A','B']});
  b.publish('A',[{subject:'scope',detail:'detail'}]);
  const encode = value => ({content:[{type:'text',text:typeof value==='string'?value:JSON.stringify(value)}]});
  const withoutAwait = async () => encode(b.read('B'));
  const withAwait = async () => encode(await b.read('B',{all:true}));
  console.log('MCP-like without await:', JSON.stringify(await withoutAwait()));
  console.log('MCP-like with await queue count:', JSON.parse((await withAwait()).content[0].text).queue.length);
  const tmp = fs.mkdtempSync(path.join(__dirname,'body-replay-'));
  const persistPath = path.join(tmp,'board.jsonl');
  const first = new DelmBoard({actors:['A','B'],persistPath});
  const item = first.reserve('A','write doc','produce a file');
  const done = first.done('A',item.item,'done',[{path:'doc.txt',content:'hello'}],'req');
  console.log('before restart content:', first.body(done.publication_id).files[0].content);
  const second = new DelmBoard({actors:['A','B'],persistPath});
  console.log('after restart queue state:', second.queueState()[0].state);
  console.log('after restart attachment keys:', Object.keys(second.body(done.publication_id).files[0]).join(','));
  console.log('after restart attachment content defined:', second.body(done.publication_id).files[0].content !== undefined);
  if (path.dirname(path.resolve(tmp)) !== path.resolve(__dirname)) throw new Error('unexpected fixture root');
  fs.unlinkSync(persistPath);
  fs.rmdirSync(tmp);
})();
